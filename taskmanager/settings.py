#   SHIZUHA_PULSE_V2_SERVICE_CREDENTIALS  JSON {"shizuha-admin": "<token>"}
#   SHIZUHA_PULSE_V2_ADMIN_SIGNING_PUBLIC_KEY           current Admin signing public key (PEM)
#   SHIZUHA_PULSE_V2_ADMIN_SIGNING_PUBLIC_KEY_PREVIOUS  previous key during rotation (optional)
def _pulse_v2_pem(value):
    """Accept a PEM blob with literal newlines or \\n escapes; '' when unset."""
    raw = str(value or '').strip()
    if not raw:
        return ''
    return raw.replace('\\n', '\n')

