def _membership_int_env(name, default, min_value=1):
    """Parse an int membership-rebalancer knob from env, failing SAFE to the
    signed default on a missing/non-numeric OR semantically-invalid value
    (PLAT-1307). Guardrail knobs must be >= min_value: a zero/negative skew, TTL,
    or cooldown would disable the guardrail or create invalid never/instantly-
    expiring behavior — so out-of-range values fall back to the signed default
    rather than crashing or silently passing a bad limit. Cooldown passes
    min_value=24 (its signed HLD floor) so it cannot be weakened below the anti-
    thrash minimum; skew/TTL use the default floor of 1."""
    raw = os.environ.get(name)
    if raw is None or raw.strip() == '':
        return default
    try:
        value = int(raw)
    except (TypeError, ValueError):
        return default
    if value < min_value:
        return default
    return value


