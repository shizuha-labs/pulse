# PLS-487 / ADR-0072: django.core.cache MUST be a shared Redis backend in
# production. Without an explicit CACHES block Django defaults to per-process
# LocMemCache, so every gunicorn worker and every Celery process holds a
# private cache. That made cache.add (used as a mutex for Alertmanager DM
# dedup, anomaly counters, org-chart snapshot locks, …) win independently in
# every process — the PLS-487 notification storm and the ≥14 distinct
# /statusz payloads measured on 2026-08-03.
#
# Backend: Django 4.2 built-in RedisCache (no django-redis dependency).
# Location: CACHE_REDIS_URL → REDIS_URL → CELERY_BROKER_URL (same source
# liveness.py already trusts), rewritten onto a dedicated DB index so cache
# keys never share the Celery broker keyspace.
# KEY_PREFIX isolates the keyspace; default TIMEOUT stays finite (300s) so
# intentional expiry is not silently broken. Call sites that need non-expiring
# counters MUST pass timeout=None explicitly (PLS-853 owns that seed change).
def _pls487_cache_redis_location() -> str:
    """Resolve the shared cache Redis URL with a dedicated DB index.

    Prefer an explicit CACHE_REDIS_URL (already used by hermetic test_settings).
    Otherwise take REDIS_URL / CELERY_BROKER_URL and pin DB index 2 so we never
    collide with the broker (typically /0) or result backend.
    """
    from urllib.parse import urlsplit, urlunsplit

    explicit = os.environ.get('CACHE_REDIS_URL')
    if explicit:
        return explicit
    base = (
        os.environ.get('REDIS_URL')
        or os.environ.get('CELERY_BROKER_URL')
        or CELERY_BROKER_URL
        or 'redis://localhost:6379/0'
    )
    parts = urlsplit(base)
    # urlsplit path is like "/0" or "/5"; force dedicated DB 2.
    return urlunsplit((parts.scheme, parts.netloc, '/2', parts.query, parts.fragment))


