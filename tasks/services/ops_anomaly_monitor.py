"""Event-driven Pulse ops-plane anomaly detection.

PLAT-1277 extends the SIEM-lite/fail-loud pattern to Pulse data-plane write
storms. The monitor runs from model write signals (no polling sweep) and submits
stable, deduplicated Pulse alerts routed to the owning team. It is deliberately
best-effort: detector failures must never block the user write path.
"""

from __future__ import annotations

import hashlib
import logging
from datetime import timedelta
from typing import Any

from django.conf import settings
from django.core.cache import cache
from django.db import transaction
from django.utils import timezone

logger = logging.getLogger(__name__)

SOURCE = 'pulse-ops-anomaly'

_TERMINAL_STATUSES = {
    'completed', 'cancelled', 'canceled', 'closed', 'done', 'resolved',
    'rejected', 'duplicate', 'wont_fix', 'merged', 'failed', 'expired',
    'deferred',
}


def _setting_int(name: str, default: int) -> int:
    try:
        return int(getattr(settings, name, default) or 0)
    except (TypeError, ValueError):
        return default


def _enabled() -> bool:
    return bool(getattr(settings, 'PULSE_OPS_ANOMALY_ALERTS_ENABLED', True))


def _item_label(item) -> str:
    return getattr(item, 'item_key', None) or str(getattr(item, 'id', 'unknown'))


def _owner_group(item) -> str:
    return (getattr(item, 'assignment_group', None) or 'devops').lower()


def _stable_hash(*parts: Any) -> str:
    raw = '\x1f'.join('' if p is None else str(p) for p in parts)
    return hashlib.sha256(raw.encode('utf-8')).hexdigest()[:16]


def _bump_window_counter(key: str, window_seconds: int) -> int:
    """Cheap write-path liveness/rate counter.

    Backed by Django's cache (Redis in production, locmem in unit tests). This
    keeps hot anomaly rules from doing COUNT/DISTINCT database confirmations on
    every write; the DB query only runs after the lightweight counter crosses
    the rule threshold.
    """
    timeout = max(1, int(window_seconds or 1))
    cache.add(key, 0, timeout=timeout)
    try:
        return int(cache.incr(key))
    except Exception:
        logger.exception('Pulse ops anomaly cache counter failed for %s', key)
        return 0


def _mark_detector_success(detector: str) -> None:
    _bump_window_counter(f'pulse-ops-anomaly:detector-success:{detector}', 3600)


def _should_skip_item(item) -> bool:
    """Avoid detector recursion on alerts generated by this detector."""
    return bool(
        getattr(item, 'mode', None) == 'alert'
        and getattr(item, 'source', None) == SOURCE
    )


def _submit_alert_on_commit(alert_data: dict[str, Any]) -> None:
    if not _enabled():
        return

    def _submit() -> None:
        try:
            from tasks.services.deduplication import AlertDeduplicationService
            from tasks.tasks import send_alert_notification

            alert, is_new = AlertDeduplicationService.submit_alert(alert_data)
            if is_new:
                send_alert_notification.delay(alert.id)
        except Exception:
            logger.exception('failed to submit Pulse ops anomaly alert')

    try:
        transaction.on_commit(_submit)
    except Exception:
        logger.exception('failed to register Pulse ops anomaly alert callback')


def record_detector_exception(detector: str, *, target: str | None = None) -> None:
    """Fail-loud path for detector exceptions.

    Signal handlers swallow detector exceptions so user writes never fail. This
    function turns those swallowed failures into the same owner-team DM path as
    real anomalies, deduped by detector, so a broken detector cannot stay silent.
    """
    _bump_window_counter(f'pulse-ops-anomaly:detector-exception:{detector}', 3600)

    class _DetectorFailureTarget:
        id = f'detector-{detector}'
        item_key = f'detector-{detector}'
        title = 'Pulse ops anomaly detector failure'
        status = 'n/a'
        project_id = None
        assignment_group = 'devops'
        mode = 'task'
        source = 'pulse-ops-anomaly-detector'

    _submit_alert_on_commit(_base_alert(
        item=_DetectorFailureTarget(),
        rule='detector_exception',
        title=f'Pulse ops anomaly detector failed: {detector}',
        description=(
            f'The Pulse ops anomaly detector `{detector}` raised on the write path '
            'and was swallowed to protect the user write. This is the fail-loud '
            'signal for PLAT-1277: detector failures must notify DevOps via the '
            'existing alert→DM path instead of remaining a log-only failure.'
        ),
        severity='error',
        labels={'detector': detector},
        payload={'detector': detector, 'target': target or 'unknown'},
    ))


def _base_alert(
    *,
    item,
    rule: str,
    title: str,
    description: str,
    severity: str = 'warning',
    labels: dict[str, Any] | None = None,
    payload: dict[str, Any] | None = None,
) -> dict[str, Any]:
    labels = labels or {}
    payload = payload or {}
    item_key = _item_label(item)
    owner_group = _owner_group(item)
    return {
        'item_type': f'alert.pulse_ops.{rule}',
        'title': title,
        'description': description,
        'source': SOURCE,
        'source_id': f'{rule}:{item_key}:{labels.get("actor_id", "")}{labels.get("notification_hash", "")}',
        'severity': severity,
        'priority': 'high' if severity in {'error', 'critical'} else 'normal',
        'project_id': getattr(item, 'project_id', None),
        'assignment_group': owner_group,
        'labels': {
            'rule': rule,
            'owner_group': owner_group,
            'item_id': str(getattr(item, 'id', '')),
            'item_key': item_key,
            **labels,
        },
        'payload': {
            'target_item_title': getattr(item, 'title', ''),
            'target_item_status': getattr(item, 'status', ''),
            'detected_at': timezone.now().isoformat(),
            **payload,
        },
        'correlation_id': f'pulse-ops-anomaly:{rule}:{item_key}',
    }


def observe_comment_created(comment) -> None:
    """Check per-item Pulse comment write rate on the comment write path."""
    if not _enabled():
        return
    item = comment.item
    if _should_skip_item(item):
        return

    threshold = _setting_int('PULSE_OPS_COMMENT_ITEM_HOURLY_THRESHOLD', 60)
    window_seconds = _setting_int('PULSE_OPS_COMMENT_ITEM_WINDOW_SECONDS', 3600)
    if threshold <= 0 or window_seconds <= 0:
        return

    approx = _bump_window_counter(
        f'pulse-ops-anomaly:comment:item:{item.id}:{window_seconds}',
        window_seconds,
    )
    _mark_detector_success('comment')
    if approx < threshold:
        return

    from tasks.models import Comment

    since = timezone.now() - timedelta(seconds=window_seconds)
    count = Comment.objects.filter(item_id=item.id, created_at__gte=since).count()
    if count < threshold:
        return

    item_key = _item_label(item)
    _submit_alert_on_commit(_base_alert(
        item=item,
        rule='per_item_comment_rate',
        title=f'Pulse comment write storm on {item_key}',
        description=(
            f'Pulse item {item_key} has {count} comments in the last '
            f'{window_seconds // 60 or 1} minute(s), crossing the configured '
            f'threshold of {threshold}. This catches PLS-207-style comment storms '
            'on the write path (no polling sweep).'
        ),
        severity='error',
        payload={
            'count': count,
            'threshold': threshold,
            'window_seconds': window_seconds,
            'latest_comment_id': str(comment.id),
            'latest_comment_author_id': comment.author_id,
            'latest_comment_author_email': comment.author_email,
        },
    ))


def observe_item_activity_created(activity) -> None:
    """Check per-item activity rate and per-actor fan-out from activity rows."""
    if not _enabled():
        return
    item = activity.item
    if _should_skip_item(item):
        return

    from tasks.models import ItemActivity

    item_threshold = _setting_int('PULSE_OPS_ACTIVITY_ITEM_HOURLY_THRESHOLD', 120)
    item_window_seconds = _setting_int('PULSE_OPS_ACTIVITY_ITEM_WINDOW_SECONDS', 3600)
    if item_threshold > 0 and item_window_seconds > 0:
        approx = _bump_window_counter(
            f'pulse-ops-anomaly:activity:item:{item.id}:{item_window_seconds}',
            item_window_seconds,
        )
        _mark_detector_success('activity')
        if approx >= item_threshold:
            since = timezone.now() - timedelta(seconds=item_window_seconds)
            count = ItemActivity.objects.filter(item_id=item.id, created_at__gte=since).count()
            if count >= item_threshold:
                item_key = _item_label(item)
                _submit_alert_on_commit(_base_alert(
                    item=item,
                    rule='per_item_activity_rate',
                    title=f'Pulse activity write storm on {item_key}',
                    description=(
                        f'Pulse item {item_key} has {count} activity rows in the last '
                        f'{item_window_seconds // 60 or 1} minute(s), crossing the '
                        f'configured threshold of {item_threshold}. Activity storms '
                        'can hide automation loops even when they are not pure comments.'
                    ),
                    severity='error',
                    payload={
                        'count': count,
                        'threshold': item_threshold,
                        'window_seconds': item_window_seconds,
                        'latest_activity_id': str(activity.id),
                        'latest_activity_action': activity.action,
                    },
                ))

    actor_threshold = _setting_int('PULSE_OPS_ACTOR_FANOUT_DISTINCT_ITEMS_THRESHOLD', 25)
    actor_window_seconds = _setting_int('PULSE_OPS_ACTOR_FANOUT_WINDOW_SECONDS', 60)
    if actor_threshold <= 0 or actor_window_seconds <= 0 or not activity.user_id:
        return

    approx = _bump_window_counter(
        f'pulse-ops-anomaly:activity:actor:{activity.user_id}:{actor_window_seconds}',
        actor_window_seconds,
    )
    if approx < actor_threshold:
        return

    since = timezone.now() - timedelta(seconds=actor_window_seconds)
    distinct_items = (
        ItemActivity.objects.filter(user_id=activity.user_id, created_at__gte=since)
        .values('item_id')
        .distinct()
        .count()
    )
    if distinct_items < actor_threshold:
        return

    item_key = _item_label(item)

    # Actor fan-out dedupes by actor rather than by whichever item happened to
    # receive the write that crossed the threshold; otherwise one runaway actor
    # could create one alert per touched item. Route these platform-level alerts
    # to DevOps while preserving the latest concrete item in the payload.
    class _ActorFanoutTarget:
        id = f'actor-{activity.user_id}'
        item_key = f'actor-{activity.user_id}'
        title = 'Pulse actor fan-out stream'
        status = 'n/a'
        project_id = None
        assignment_group = 'devops'
        mode = 'task'
        source = 'pulse-activity'

    _submit_alert_on_commit(_base_alert(
        item=_ActorFanoutTarget(),
        rule='per_actor_activity_fanout',
        title=f'Pulse actor fan-out anomaly from user {activity.user_id}',
        description=(
            f'Actor {activity.user_id} wrote activity on {distinct_items} distinct Pulse '
            f'items in {actor_window_seconds}s, crossing the configured threshold of '
            f'{actor_threshold}. This detects runaway automation touching many items.'
        ),
        severity='warning',
        labels={'actor_id': str(activity.user_id)},
        payload={
            'distinct_items': distinct_items,
            'threshold': actor_threshold,
            'window_seconds': actor_window_seconds,
            'actor_email': activity.user_email,
            'latest_activity_id': str(activity.id),
            'latest_item_id': str(item.id),
            'latest_item_key': item_key,
        },
    ))


def observe_notification_created(notification) -> None:
    """Check repeated identical notifications to the same recipient."""
    if not _enabled():
        return
    item = notification.item
    if item is not None and _should_skip_item(item):
        return

    threshold = _setting_int('PULSE_OPS_IDENTICAL_NOTIFICATION_THRESHOLD', 8)
    window_seconds = _setting_int('PULSE_OPS_IDENTICAL_NOTIFICATION_WINDOW_SECONDS', 300)
    if threshold <= 0 or window_seconds <= 0:
        return

    notif_hash = _stable_hash(
        notification.user_id,
        notification.notification_type,
        notification.title,
        notification.message,
    )
    approx = _bump_window_counter(
        f'pulse-ops-anomaly:notification:{notif_hash}:{window_seconds}',
        window_seconds,
    )
    _mark_detector_success('notification')
    if approx < threshold:
        return

    from tasks.models import Notification

    since = timezone.now() - timedelta(seconds=window_seconds)
    count = Notification.objects.filter(
        user_id=notification.user_id,
        notification_type=notification.notification_type,
        title=notification.title,
        message=notification.message,
        created_at__gte=since,
    ).count()
    if count < threshold:
        return

    target_item = item
    if target_item is None:
        # Build a pseudo-item-like object with enough attributes for routing.
        class _NotificationTarget:
            id = f'notification-user-{notification.user_id}'
            item_key = f'notification-user-{notification.user_id}'
            title = 'Pulse notification stream'
            status = 'n/a'
            project_id = None
            assignment_group = 'devops'
            mode = 'task'
            source = 'pulse-notification'
        target_item = _NotificationTarget()

    _submit_alert_on_commit(_base_alert(
        item=target_item,
        rule='identical_notification_storm',
        title=f'Pulse repeated notification storm to user {notification.user_id}',
        description=(
            f'Pulse sent {count} identical {notification.notification_type} notifications '
            f'to user {notification.user_id} in {window_seconds}s, crossing the configured '
            f'threshold of {threshold}. This detects noisy notification loops on the write path.'
        ),
        severity='warning',
        labels={
            'recipient_user_id': str(notification.user_id),
            'notification_type': notification.notification_type,
            'notification_hash': notif_hash,
        },
        payload={
            'count': count,
            'threshold': threshold,
            'window_seconds': window_seconds,
            'latest_notification_id': notification.id,
            'title': notification.title,
            'message_preview': (notification.message or '')[:300],
        },
    ))


# Intentional parking holds — not "queue flood" signal for PLS-254 depth.
# security-ci floods sat in accepted/found (still counted). Blocked Focused-QA
# waiting on upstream and calendar `scheduled` holds must not inflate Attention.
_WAITING_DEPTH_STATUS_SLUGS = frozenset({
    'blocked',
    'scheduled',
    'waiting_external',
    'backlog',
})


def _active_items_queryset():
    from tasks.models import Item

    return Item.objects.filter(mode='task', is_archived=False).exclude(status__in=_TERMINAL_STATUSES)


def _assignee_depth_queryset(item):
    """Active non-terminal items on this assignee that count toward flood depth.

    Excludes waiting/parking statuses (blocked, scheduled, …): those are
    awareness holds, not misroute floods. Flood detection still sees
    accepted/found/open/todo/in_progress/etc. across any workflow/identity.
    """
    qs = _active_items_queryset().exclude(status__in=_WAITING_DEPTH_STATUS_SLUGS)
    if getattr(item, 'assignee_id', None):
        return qs.filter(assignee_id=item.assignee_id)
    return qs.filter(assignee_email__iexact=(item.assignee_email or '').strip())


def observe_item_saved(item, *, created: bool = False) -> None:
    """Check queue-depth invariants on the item write path (PLS-254).

    These rules deliberately count active *actionable* items in any workflow
    and on any identity (including service accounts) because the security-ci
    flood sat in security-finding `accepted` on non-roster/service identities,
    where ordinary ready-queue rebalancers are not supposed to act.

    Waiting/parking statuses (blocked, scheduled, backlog, waiting_external)
    are excluded from the depth count — long dwell there is expected and must
    not fire Attention as a "queue-depth anomaly".
    """
    if not _enabled() or _should_skip_item(item):
        return

    _mark_detector_success('item')
    _check_assignee_active_depth(item)
    _check_source_active_flood(item)
    _check_assignment_group_jump(item)


def _resolve_assignee_depth_alerts(item, *, count: int, threshold: int) -> None:
    """Clear stale assignee-depth alerts once the plate is back under threshold.

    No-ops (and does not register an on_commit) when no matching firing alert
    exists — callers create items frequently, and a free on_commit on every
    healthy write would inflate callback counts and race unrelated commit hooks.
    """
    assignee_id = str(getattr(item, 'assignee_id', '') or '')
    assignee_email = (getattr(item, 'assignee_email', '') or '').strip()
    if not assignee_id and not assignee_email:
        return

    matchers = {'rule': 'assignee_active_item_depth'}
    if assignee_id:
        matchers['assignee_id'] = assignee_id
    elif assignee_email:
        matchers['assignee_email'] = assignee_email

    try:
        from tasks.services.deduplication import AlertDeduplicationService
        if not AlertDeduplicationService._find_alerts_by_labels(matchers, SOURCE):
            return
    except Exception:
        logger.exception('failed to probe assignee-depth alerts for recovery')
        return

    def _resolve() -> None:
        try:
            from tasks.services.deduplication import AlertDeduplicationService
            AlertDeduplicationService.handle_recovery({
                'source': SOURCE,
                'resolve_matchers': matchers,
                'resolution_note': (
                    f'Assignee depth recovered to {count} actionable items '
                    f'(threshold {threshold}); waiting/parking statuses excluded.'
                ),
            })
        except Exception:
            logger.exception('failed to resolve assignee-depth anomaly on recovery')

    try:
        transaction.on_commit(_resolve)
    except Exception:
        logger.exception('failed to register assignee-depth recovery callback')


def _check_assignee_active_depth(item) -> None:
    threshold = _setting_int('PULSE_OPS_ASSIGNEE_ACTIVE_ITEM_THRESHOLD', 50)
    if threshold <= 0 or not (getattr(item, 'assignee_id', None) or getattr(item, 'assignee_email', None)):
        return

    qs = _assignee_depth_queryset(item)
    count = qs.count()
    if count <= threshold:
        # Recover sticky Attention rows when the plate is healthy again.
        _resolve_assignee_depth_alerts(item, count=count, threshold=threshold)
        return

    assignee_label = getattr(item, 'assignee_email', None) or getattr(item, 'assignee_id', None)

    class _AssigneeDepthTarget:
        id = f'assignee-depth-{assignee_label}'
        item_key = f'assignee-depth-{assignee_label}'
        title = 'Pulse assignee active-item depth'
        status = 'n/a'
        project_id = None
        assignment_group = getattr(item, 'assignment_group', None) or 'devops'
        mode = 'task'
        source = 'pulse-item-depth'

    _submit_alert_on_commit(_base_alert(
        item=_AssigneeDepthTarget(),
        rule='assignee_active_item_depth',
        title=f'Pulse assignee queue-depth anomaly: {assignee_label}',
        description=(
            f'Assignee {assignee_label} has {count} actionable Pulse items '
            f'(excluding blocked/scheduled/waiting holds) across all workflows, '
            f'crossing the configured threshold of {threshold}. '
            'This is the PLS-254 fail-loud guard for service-token/misroute floods '
            'that normal ready-queue rebalancers may legitimately not touch.'
        ),
        severity='error',
        labels={
            'assignee_id': str(getattr(item, 'assignee_id', '') or ''),
            'assignee_email': (getattr(item, 'assignee_email', '') or ''),
            'assignment_group': (getattr(item, 'assignment_group', '') or ''),
        },
        payload={
            'active_count': count,
            'threshold': threshold,
            'latest_item_id': str(getattr(item, 'id', '')),
            'latest_item_key': _item_label(item),
            'excluded_waiting_statuses': sorted(_WAITING_DEPTH_STATUS_SLUGS),
        },
    ))


# Human/UI-created tasks are not an auto-filer flood. `source=manual` is the
# default for operator/agent-authored work; treating it as a 24h flood produced
# a sticky 5660× Attention row while the org was just… filing tasks.
_IGNORED_SOURCE_FLOOD_SOURCES = frozenset({
    '',
    'manual',
    'ui',
    'web',
    'human',
    'pulse-item-depth',
    'pulse-source-depth',
    'pulse-group-depth',
    'pulse-notification',
    'pulse-activity',
})


def _check_source_active_flood(item) -> None:
    source = (getattr(item, 'source', None) or '').strip()
    threshold = _setting_int('PULSE_OPS_SOURCE_ACTIVE_24H_THRESHOLD', 100)
    window_seconds = _setting_int('PULSE_OPS_SOURCE_ACTIVE_WINDOW_SECONDS', 86400)
    if threshold <= 0 or window_seconds <= 0 or not source:
        return
    if source.lower() in _IGNORED_SOURCE_FLOOD_SOURCES:
        return

    since = timezone.now() - timedelta(seconds=window_seconds)
    count = _active_items_queryset().filter(source=source, created_at__gte=since).count()
    if count <= threshold:
        return

    source_target = type('SourceFloodTarget', (), {
        'id': f'source-flood-{source}',
        'item_key': f'source-flood-{source}',
        'title': 'Pulse source active-item flood',
        'status': 'n/a',
        'project_id': None,
        'assignment_group': getattr(item, 'assignment_group', None) or 'devops',
        'mode': 'task',
        'source': 'pulse-source-depth',
    })()

    _submit_alert_on_commit(_base_alert(
        item=source_target,
        rule='source_active_24h_flood',
        title=f'Pulse source flood anomaly: {source}',
        description=(
            f'Source `{source}` produced {count} active Pulse items in the last '
            f'{window_seconds // 3600 or 1} hour(s), crossing the configured '
            f'threshold of {threshold}. This catches auto-filer/migration floods '
            'even when items are spread across assignees or statuses.'
        ),
        severity='error',
        labels={'source': source, 'assignment_group': (getattr(item, 'assignment_group', '') or '')},
        payload={
            'active_count_24h': count,
            'threshold': threshold,
            'window_seconds': window_seconds,
            'latest_item_id': str(getattr(item, 'id', '')),
            'latest_item_key': _item_label(item),
        },
    ))


def _check_assignment_group_jump(item) -> None:
    group = (getattr(item, 'assignment_group', None) or '').strip().lower()
    min_count = _setting_int('PULSE_OPS_GROUP_24H_JUMP_MIN', 50)
    ratio = _setting_int('PULSE_OPS_GROUP_24H_JUMP_RATIO', 3)
    if min_count <= 0 or ratio <= 0 or not group:
        return

    now = timezone.now()
    day_ago = now - timedelta(hours=24)
    week_ago = now - timedelta(days=8)
    base = _active_items_queryset().filter(assignment_group=group)
    recent = base.filter(created_at__gte=day_ago).count()
    if recent < min_count:
        return
    previous_7d = base.filter(created_at__gte=week_ago, created_at__lt=day_ago).count()
    daily_baseline = max(1, previous_7d / 7.0)
    if recent < ratio * daily_baseline:
        return

    class _GroupJumpTarget:
        id = f'group-jump-{group}'
        item_key = f'group-jump-{group}'
        title = 'Pulse assignment-group queue jump'
        status = 'n/a'
        project_id = None
        assignment_group = group
        mode = 'task'
        source = 'pulse-group-depth'

    _submit_alert_on_commit(_base_alert(
        item=_GroupJumpTarget(),
        rule='assignment_group_24h_jump',
        title=f'Pulse assignment-group queue jump: {group}',
        description=(
            f'Assignment group `{group}` has {recent} active items created in the '
            f'last 24h versus a previous-7d daily baseline of {daily_baseline:.1f}, '
            f'crossing the configured {ratio}× jump threshold. This is the PLS-254 '
            'fail-loud guard for sudden queue piles.'
        ),
        severity='warning',
        labels={'assignment_group': group},
        payload={
            'recent_24h_active_count': recent,
            'previous_7d_active_count': previous_7d,
            'daily_baseline': daily_baseline,
            'ratio_threshold': ratio,
            'min_count': min_count,
            'latest_item_id': str(getattr(item, 'id', '')),
            'latest_item_key': _item_label(item),
        },
    ))
